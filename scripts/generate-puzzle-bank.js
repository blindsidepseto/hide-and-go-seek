// Builds src/game/puzzle-bank.ts. Run with `npm run puzzles` (compiles the game code first).
// Usage: node scripts/generate-puzzle-bank.js [puzzlesPerSize] [seed]
const fs = require('fs');
const path = require('path');

const build = path.resolve(__dirname, '../.puzzle-build');
const { generatePuzzle } = require(path.join(build, 'generator'));
const { encodePuzzle } = require(path.join(build, 'puzzles'));
const { createRng } = require(path.join(build, 'rng'));
const { MIN_SIZE, MAX_SIZE } = require(path.join(build, 'types'));

const perSize = Number(process.argv[2] || 20);
const rng = createRng(Number(process.argv[3] || 20261021));
const bank = {};

for (let size = MIN_SIZE; size <= MAX_SIZE; size += 1) {
  const seen = new Set();
  const started = Date.now();
  while (seen.size < perSize) {
    seen.add(encodePuzzle(generatePuzzle(size, rng)));
  }
  bank[size] = [...seen];
  console.log(`${size}x${size}: ${perSize} puzzles in ${((Date.now() - started) / 1000).toFixed(1)}s`);
}

const out = path.resolve(__dirname, '../src/game/puzzle-bank.ts');
fs.writeFileSync(out, `// Generated by scripts/generate-puzzle-bank.js. Do not edit by hand.
export const PUZZLE_BANK_DATA: Record<number, string[]> = ${JSON.stringify(bank, null, 2)};
`);
console.log(`Wrote ${out}`);
